test('missed day uses a freeze; moving clock back cannot retroactively log', async ({ page }) => {
  let seeded = initialState('2026-10-09')
  seeded = act(seeded, '2026-10-09', { type: 'add', subject: 'english', count: 50 })
  seeded = act(seeded, '2026-10-09', { type: 'add', subject: 'math', count: 20 })
  seeded = reconcile(seeded, '2026-10-11')
  await page.addInitScript(({ key, state }) => localStorage.setItem(key, JSON.stringify(state)), { key: STORAGE_KEY, state: seeded })
  await page.clock.setFixedTime(new Date('2026-10-11T09:00:00Z'))
  await page.goto('/')
  await expect(page.locator('.summary-card.streak-card')).toContainText('0/2 freezes')
  await expect(page.locator('.summary-card.streak-card .summary-value strong')).toHaveText('1')
  await page.getByRole('button', { name: 'October 10, 2026: frozen', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Protected by a streak freeze')
  await page.keyboard.press('Escape')
  await page.clock.setFixedTime(new Date('2026-10-10T09:00:00Z'))
  await page.reload()
  await expect(page.locator('.notice')).toContainText('Logging is paused')
  await expect(page.getByRole('button', { name: 'Add 5 english questions', exact: true })).toBeDisabled()
})
