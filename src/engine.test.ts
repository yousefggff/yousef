import { describe, expect, it } from 'vitest'
import { act, addDays, complete, count, dateKey, dayDiff, dayXP, decode, getDay, initialState, level, load, reconcile, save, START, STORAGE_KEY, streaks, totalXP, updateSettings, weekStart, weekStats } from './engine'
import type { State } from './engine'
function finish(s: State, key: string) {
  s = reconcile(s, key)
  const d = getDay(s, key)
  if (d.practice) return act(s, key, { type: 'test', completed: true, english: 650, math: 750 })
  s = act(s, key, { type: 'add', subject: 'english', count: d.englishTarget })
  return act(s, key, { type: 'add', subject: 'math', count: d.mathTarget })
}
describe('progress and rewards', () => {
  it('uses Friday targets and derives every bonus exactly once', () => {
    let s = finish(initialState(START), START)
    expect(dayXP(s.days[START])).toBe(900)
    expect(streaks(s, START).current).toBe(1)
    s = act(s, START, { type: 'add', subject: 'math', count: 10 })
    expect(totalXP(s)).toBe(1000)
    expect(streaks(s, START).current).toBe(1)
    expect(totalXP(reconcile(reconcile(s, START), START))).toBe(1000)
  })
  it('undo reverses questions and subject/daily bonuses without removing history', () => {
    let s = finish(initialState(START), START)
    s = act(s, START, { type: 'undo', subject: 'math' })
    expect(totalXP(s)).toBe(550)
    expect(streaks(s, START).current).toBe(0)
    expect(count(s.days[START], 'english')).toBe(50)
    expect(s.achievements.first).toBe(START)
    s = finish(s, START)
    expect(s.achievements.first).toBe(START)
  })
  it('preserves target snapshots when settings change', () => {
    let s = initialState(START)
    s = act(s, START, { type: 'add', subject: 'english', count: 5 })
    s = updateSettings(s, { ...s.settings, english: 10, fridayEnglish: 15 }, START)
    expect(s.days[START].englishTarget).toBe(50)
    expect(count(s.days[START], 'english')).toBe(5)
    expect(getDay(s, '2026-10-10').englishTarget).toBe(10)
  })
  it('does not let review tasks alter streak or XP', () => {
    const s = act(initialState(START), START, { type: 'review', index: 0 })
    expect(totalXP(s)).toBe(0)
    expect(streaks(s, START).current).toBe(0)
  })
  it('awards full-week XP once and reverses it on undo', () => {
    let s = initialState('2026-10-12')
    for (let i = 0; i < 7; i++) s = finish(s, addDays('2026-10-12', i))
    expect(weekStats(s, '2026-10-12').xp).toBe(4600)
    expect(s.achievements.perfect).toBe('2026-10-18')
    s = act(s, '2026-10-18', { type: 'undo', subject: 'math' })
    expect(weekStats(s, '2026-10-12').xp).toBe(4000)
  })
  it('practice days replace questions and receive the daily bonus', () => {
    let s = initialState('2026-10-16')
    s = act(s, '2026-10-16', { type: 'add', subject: 'math', count: 20 })
    expect(count(s.days['2026-10-16'], 'math')).toBe(0)
    s = finish(s, '2026-10-16')
    expect(complete(s.days['2026-10-16'])).toBe(true)
    expect(totalXP(s)).toBe(100)
    expect(streaks(s, '2026-10-16').current).toBe(1)
    s = act(s, '2026-10-16', { type: 'test', completed: false, english: null, math: null })
    expect(totalXP(s)).toBe(0)
  })
  it('has progressively increasing level requirements', () => {
    expect(level(499).current).toBe(1)
    expect(level(500)).toMatchObject({ current: 2, remaining: 0, needed: 650 })
    expect(level(1150).current).toBe(3)
  })
})
describe('streaks and local dates', () => {
  it('keeps yesterday’s streak while today is pending; freeze preserves without increasing', () => {
    let s = finish(initialState(START), START)
    s = reconcile(s, '2026-10-10')
    expect(streaks(s, '2026-10-10').current).toBe(1)
    s = reconcile(s, '2026-10-11')
    expect(s.days['2026-10-10'].frozen).toBe(true)
    expect(streaks(s, '2026-10-11')).toMatchObject({ current: 1, freezes: 0 })
    s = reconcile(s, '2026-10-12')
    expect(streaks(s, '2026-10-12')).toMatchObject({ current: 0, longest: 1 })
  })
  it('earns a freeze per seven completed days with capacity two', () => {
    let s = initialState(START)
    for (let i = 0; i < 14; i++) s = finish(s, addDays(START, i))
    expect(streaks(s, '2026-10-22')).toMatchObject({ current: 14, freezes: 2 })
    s = reconcile(s, '2026-10-26')
    expect(streaks(s, '2026-10-26')).toMatchObject({ current: 0, longest: 14, freezes: 0 })
    expect(s.days['2026-10-23'].frozen).toBe(true)
    expect(s.days['2026-10-24'].frozen).toBe(true)
    expect(s.days['2026-10-25'].frozen).toBe(false)
  })
  it('does not refill inventory on repeated refresh', () => {
    let s = initialState(START)
    for (let i = 0; i < 7; i++) s = finish(s, addDays(START, i))
    s = reconcile(s, '2026-10-17')
    const before = streaks(s, '2026-10-17')
    expect(streaks(reconcile(s, '2026-10-17'), '2026-10-17')).toEqual(before)
  })
  it('rejects retroactive actions after the local date moves backwards', () => {
    const s = reconcile(finish(initialState(START), START), '2026-10-11')
    expect(act(s, '2026-10-10', { type: 'add', subject: 'math', count: 100 })).toEqual(s)
    expect(reconcile(s, START)).toEqual(s)
  })
  it('handles month boundaries and DST using calendar days', () => {
    expect(addDays('2026-10-31', 1)).toBe('2026-11-01')
    expect(dayDiff('2026-10-09', '2026-11-07')).toBe(29)
    expect(weekStart('2026-11-01')).toBe('2026-10-26')
    expect(dateKey(new Date(2026, 9, 9, 23, 59))).toBe(START)
  })
  it('does not create or reward study days on or after the exam', () => {
    const s = initialState('2026-11-07')
    expect(s.days['2026-11-07']).toBeUndefined()
    expect(totalXP(act(s, '2026-11-07', { type: 'add', subject: 'math', count: 100 }))).toBe(0)
  })
})
describe('persistence and imports', () => {
  it('round-trips progress and does not award twice on reopen', () => {
    const s = finish(initialState(START), START)
    const data = new Map<string, string>()
    const storage = { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string, v: string) => { data.set(k, v) } }
    save(storage, s)
    expect(data.has(STORAGE_KEY)).toBe(true)
    expect(load(storage, START)).toEqual(s)
    expect(totalXP(load(storage, START))).toBe(900)
  })
  it('rejects malformed files, dates, actions, and unsupported versions', () => {
    expect(() => decode('{')).toThrow()
    expect(() => decode('{"version":2}')).toThrow()
    const s = initialState(START)
    s.days[START].actions.push({ subject: 'math', count: -1 })
    expect(() => decode(JSON.stringify(s))).toThrow()
    const s2 = initialState(START)
    s2.settings.exam = '2026-02-31'
    expect(() => decode(JSON.stringify(s2))).toThrow()
  })
})
