test('two tabs serialize progress changes without losing either entry', async ({ page, context }) => {
  await page.goto('/')
  const other = await context.newPage()
  await other.clock.setFixedTime(fixed)
  await other.goto('/')
  await Promise.all([page.getByRole('button', { name: 'Add 5 english questions', exact: true }).click(), other.getByRole('button', { name: 'Add 10 math questions', exact: true }).click()])
  await expect(page.getByRole('img', { name: 'english: 5 of 50 questions', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: 'math: 10 of 20 questions', exact: true })).toBeVisible()
  await expect(other.getByRole('img', { name: 'english: 5 of 50 questions', exact: true })).toBeVisible()
  await other.close()
})
