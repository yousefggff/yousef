import { test, expect } from '@playwright/test'
import { initialState, act, reconcile, STORAGE_KEY, totalXP } from '../src/engine'
const fixed = new Date('2026-10-09T09:00:00Z')
test.beforeEach(async ({ page }) => { await page.clock.setFixedTime(fixed) })
test('logs questions, completes a mission, persists and reverses XP on undo', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('img', { name: 'english: 0 of 50 questions', exact: true })).toBeVisible()
  await page.getByLabel('Custom english question count').fill('50')
  await page.locator('.tracker.english').getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Hello, level 2!')
  await page.getByRole('button', { name: 'Keep the momentum' }).click()
  await page.getByLabel('Custom math question count').fill('20')
  await page.locator('.tracker.math').getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Daily mission complete!')
  await expect(page.getByRole('dialog')).toContainText('70 questions · 900 XP today · 1-day streak')
  await page.getByRole('button', { name: 'Keep the momentum' }).click()
  await expect(page.locator('.summary-card.streak-card .summary-value strong')).toHaveText('1')
  await page.reload()
  await expect(page.getByRole('img', { name: 'english: 50 of 50 questions', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo last math entry' }).click()
  await expect(page.getByRole('img', { name: 'math: 0 of 20 questions', exact: true })).toBeVisible()
  const stored = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), STORAGE_KEY)
  expect(totalXP(stored)).toBe(550)
  expect(errors).toEqual([])
})
